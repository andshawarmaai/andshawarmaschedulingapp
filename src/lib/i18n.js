// Two-language (en/es) dictionary for the staff-facing app — Home,
// Schedule, Swap, Time Off, and Login. The admin/Manage side stays
// English-only on purpose (see CLAUDE.md): the owner asked for "anybody"
// using the staff app to be able to flip a simple switch, not a per-account
// setting, so the language lives in a plain cookie (see getLang/LANG_COOKIE)
// rather than the users table — no schema change, works before login too.
//
// Isomorphic on purpose: imported both from Astro frontmatter (server
// render, via getLang(Astro)) and from page <script> modules (client, via
// window.__lang set by a tiny inline script each page includes) — same
// dictionary, same t() function, so the two can never say different things.

export const LANG_COOKIE = 'shawarma_lang';

export const LANGS = ['en', 'es'];

export function getLang(Astro) {
  const v = Astro.cookies.get(LANG_COOKIE)?.value;
  return v === 'es' ? 'es' : 'en';
}

