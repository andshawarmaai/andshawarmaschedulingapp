export const DICTS = { en, es };

export function t(lang, key, vars) {
  const dict = DICTS[lang] || DICTS.en;
  let s = dict[key] ?? DICTS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, v);
    }
  }
  return s;
}
